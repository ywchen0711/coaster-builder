// Builds js/presets.js: each example starts with a hand-made prefix and the auto-complete search closes the circuit.
// node tools/gen-presets.mjs
import { writeFileSync } from 'fs';
import { build, autoComplete } from '../js/track.js';
import { simulate } from '../js/sim.js';

const P = (str) => str.trim().split(/\s+/).map((w) => ({ t: w.replace(/[*^]/g, ''), ...(w.includes('*') ? { chain: true } : {}), ...(w.includes('^') ? { bank: true } : {}) }));
const DEFS = [
  { id: 'family', color: '#ff5a5a', name: { zh: '家庭小飛車', en: 'Family Coaster' }, prefix: 'S U* S* S* D* D S U RR^ RR^ S U D S D S' },
  { id: 'loops', color: '#3a7aff', name: { zh: '三圈翻轉王', en: 'Triple Loop' }, prefix: 'S U* U* S* S* D* D* RR^ RR^ D D S U U S O S O S O S K K' },
  { id: 'hills', color: '#2ec85a', name: { zh: '失重小山丘', en: 'Airtime Hills' }, prefix: 'S U* U* S* S* D* D* RR^ RR^ D D S U U U D D U U D D U' },
  { id: 'speed', color: '#ffb02a', name: { zh: '極速巨人', en: 'Speed Giant' }, prefix: 'S U* U* S* S* S* S* D* D* RR^ RR^ D D S S S S U U S S K K RR^ RR^' },
];
const out = [];
for (const d of DEFS) {
  const pre = P(d.prefix);
  const L = build(pre);
  if (L.error) { console.log(d.id, 'prefix error', L.error); process.exit(1); }
  const tail = autoComplete(L, 80000);
  if (!tail) { console.log(d.id, 'auto-complete failed'); process.exit(1); }
  const pieces = pre.concat(tail);
  const r = simulate(build(pieces));
  console.log(d.id.padEnd(7), pieces.length, 'pieces', r.complete ? 'complete' : 'STALL ' + JSON.stringify(r.stalled && { y: r.stalled.y, seg: r.stalled.seg }), 'top', r.stats.maxSpeedKmh.toFixed(0), 'km/h',
    'inv', r.stats.inversions, 'air', r.stats.airtime.toFixed(1), 'E', r.ratings.excitement.toFixed(1), 'I', r.ratings.intensity.toFixed(1), 'N', r.ratings.nausea.toFixed(1),
    r.reviews.map((v) => v.id + v.stars).join(' '));
  out.push({ id: d.id, color: d.color, name: d.name, pieces });
}
writeFileSync(new URL('../js/presets.js', import.meta.url), '// generated by tools/gen-presets.mjs\nexport const PRESETS = ' + JSON.stringify(out) + ';\n');
console.log('wrote js/presets.js');
